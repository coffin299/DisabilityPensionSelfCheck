export function getItemById(id: ItemId): JudgmentItem {
  const item = JUDGMENT_ITEMS.find((entry) => entry.id === id)
  if (!item) {
    throw new Error(`Unknown item id: ${id}`)
  }
  return item
}

export function getOptionLabel(itemId: ItemId, score: Score): string {
  const item = getItemById(itemId)
  const option = item.options.find((entry) => entry.value === score)
  if (!option) {
    throw new Error(`Unknown score ${score} for item ${itemId}`)
  }
  return option.label
}

export type Score = 1 | 2 | 3 | 4

export type DegreeLevel = 1 | 2 | 3 | 4 | 5

export type DisabilityType = 'mental' | 'intellectual'

export type ItemId =
  | 'meal'
  | 'hygiene'
  | 'money'
  | 'medication'
  | 'communication'
  | 'safety'
  | 'social'

export interface ScaleOption {
  value: Score
  /** 公式評価尺度のラベル */
  label: string
  /** 記載要領に記載された説明 */
  description: string
}

export interface JudgmentItem {
  id: ItemId
  number: number
  title: string
  /** 診断書様式上の補足（ある場合） */
  formNote?: string
  options: ScaleOption[]
}

export interface DegreeOption {
  value: DegreeLevel
  label: string
}

